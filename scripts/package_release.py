#!/usr/bin/env python3
"""Deterministic release packaging for openre, portable to every runner.

Stages the same archive layout for every platform and writes either a
.tar.gz (unix targets) or a .zip (Windows targets), plus a .sha256 sidecar.
Both formats are written with fixed metadata - epoch mtimes, root owner,
normalized permissions, sorted entries, timestamp-free gzip - so re-running
the packager over the same inputs is byte-stable.

Usage:
  scripts/package_release.py --name openre-0.1.0-x86_64-unknown-linux-gnu \
      --binary target/release/openre \
      --binary target/release/openre-tui \
      --binary target/release/sentinel \
      --completions-dir completions-gen [--format tar.gz] [--out dist]

Each binary keeps its name inside the archive, exactly as passed via
--binary (openre, openre-tui, sentinel; the .exe spellings under
--format zip). The completions directory must already hold the four
generated completion files (produced by a host build, see
.github/workflows/release.yml); the README for them lives here so every
archive ships identical instructions.
"""
import argparse
import gzip
import hashlib
import shutil
import tarfile
import tempfile
import time
import zipfile
from io import BytesIO
from pathlib import Path

COMPLETIONS_README = """Shell completions for openre.

Generated by the build that produced this archive; the script covers the
subcommands and flags of exactly that build, so reinstall after upgrading.

  bash         install as ~/.local/share/bash-completion/completions/openre
               (create the directory first if it does not exist)
  zsh          install as ~/.zfunc/_openre, with ~/.zfunc in fpath before
               compinit runs
  fish         install as ~/.config/fish/completions/openre.fish
  powershell   dot-source from your $PROFILE, or append to it

The archive also carries openre-tui and sentinel; the completions cover the
openre CLI. The docs/ directory holds the platform documentation.
"""

COMPLETION_NAMES = {
    "bash": "openre.bash",
    "zsh": "_openre",
    "fish": "openre.fish",
    "powershell": "openre.ps1",
}


def stage(name: str, binaries: list[Path], completions_dir: Path, repo: Path,
          fmt: str) -> tuple[Path, Path]:
    """Assemble the archive root; returns (staging dir, archive root)."""
    stage_root = Path(tempfile.mkdtemp(prefix="openre-pkg-"))
    root = stage_root / name
    (root / "completions").mkdir(parents=True)
    (root / "docs").mkdir()

    # The archive entries are named after the --binary arguments, whatever
    # the building host prefixed the paths with.
    seen = set()
    for binary in binaries:
        if binary.name in seen:
            raise SystemExit(f"duplicate binary name: {binary.name}")
        seen.add(binary.name)
        shutil.copy2(binary, root / binary.name)
    for shell, out in COMPLETION_NAMES.items():
        src = completions_dir / out
        if not src.is_file():
            raise SystemExit(f"missing generated completion: {src}")
        shutil.copy2(src, root / "completions" / out)
    (root / "completions" / "README").write_text(COMPLETIONS_README, encoding="utf-8")
    for pattern in ("*.md", "*.svg", "*.1"):
        for f in sorted((repo / "docs").glob(pattern)):
            shutil.copy2(f, root / "docs" / f.name)
    for f in ("LICENSE", "README.md"):
        src = repo / f
        if not src.is_file():
            raise SystemExit(f"missing {src}")
        shutil.copy2(src, root / f)
    # Optional: open-re ships no changelog yet, archives grow one when it lands.
    changelog = repo / "CHANGELOG.md"
    if changelog.is_file():
        shutil.copy2(changelog, root / "CHANGELOG.md")
    return stage_root, root


def normalize(root: Path, exes: list[Path]) -> None:
    """Fixed permissions so the archive does not depend on the builder's umask."""
    for p in root.rglob("*"):
        p.chmod(0o755 if p.is_dir() else 0o644)
    for exe in exes:
        exe.chmod(0o755)


def sorted_members(root: Path) -> list[Path]:
    # Directories sort before their contents: python's zipfile extractor
    # creates members in archive order and chokes if a directory entry
    # arrives after files it would have contained.
    return sorted(root.rglob("*"), key=lambda p: (not p.is_dir(), str(p.relative_to(root))))


def write_tar_gz(root: Path, name: str, out_dir: Path) -> Path:
    """Fixed tar (GNU format, epoch mtimes, root owner) through a
    timestamp-free gzip stream. Members carry the <name>/ prefix so an
    unpack lands in one directory."""
    buf = BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.GNU_FORMAT) as tar:
        for p in sorted_members(root):
            ti = tar.gettarinfo(str(p), arcname=f"{name}/{p.relative_to(root).as_posix()}")
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            ti.mtime = 0
            if p.is_file():
                ti.size = p.stat().st_size
                with p.open("rb") as src:
                    tar.addfile(ti, src)
            else:
                tar.addfile(ti)
    dest = out_dir / f"{name}.tar.gz"
    with dest.open("wb") as f:
        with gzip.GzipFile(fileobj=f, mode="wb", filename="", mtime=0, compresslevel=9) as gz:
            gz.write(buf.getvalue())
    return dest


def write_zip(root: Path, name: str, out_dir: Path) -> Path:
    """Fixed zip: 1980-epoch timestamps, explicit unix permission bits."""
    dest = out_dir / f"{name}.zip"
    with zipfile.ZipFile(dest, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted_members(root):
            rel = p.relative_to(root).as_posix()
            # Directory entries need the trailing slash - python's zipfile
            # decides dir-ness by that suffix alone, and without it the
            # extractor creates a file named "completions" and then fails
            # to put "completions/README" inside it. normalize() has just
            # set the executables 0755 and everything else 0644, so the
            # exec bit is the deterministic executable marker here.
            arc = f"{name}/{rel}{'/' if p.is_dir() else ''}"
            zi = zipfile.ZipInfo(arc, date_time=(1980, 1, 1, 0, 0, 0))
            mode = 0o755 if p.is_dir() or (p.is_file() and p.stat().st_mode & 0o111) else 0o644
            zi.external_attr = (mode << 16) | (0x10 if p.is_dir() else 0)
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, p.read_bytes() if p.is_file() else b"")
    return dest


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    repo = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", required=True,
                    help="archive stem, e.g. openre-0.1.0-aarch64-apple-darwin")
    ap.add_argument("--binary", required=True, action="append", type=Path,
                    help="built binary to package; repeat once per binary")
    ap.add_argument("--completions-dir", required=True, type=Path,
                    help="directory holding the four generated completion files")
    ap.add_argument("--format", choices=("tar.gz", "zip"), default="tar.gz")
    ap.add_argument("--out", type=Path, default=Path("dist"))
    args = ap.parse_args()

    binaries = []
    for b in args.binary:
        if not b.is_file():
            raise SystemExit(f"no binary at {b}")
        binaries.append(b.resolve())

    args.out.mkdir(parents=True, exist_ok=True)
    stage_root, root = stage(args.name, binaries,
                             args.completions_dir.resolve(), repo, args.format)
    try:
        exes = [root / b.name for b in binaries]
        normalize(root, exes)
        t0 = time.time()
        archive = (write_zip(root, args.name, args.out) if args.format == "zip"
                   else write_tar_gz(root, args.name, args.out))
        sidecar = args.out / f"{archive.name}.sha256"
        sidecar.write_text(f"{sha256_file(archive)}  {archive.name}\n", encoding="utf-8")
        print(f"packaged {archive.name} ({archive.stat().st_size // (1024 * 1024)} MiB) "
              f"in {time.time() - t0:.1f}s")
    finally:
        shutil.rmtree(stage_root)


if __name__ == "__main__":
    main()
